"""Postgres access, schema, CSV seed, export and reset."""
import csv
import os
from datetime import date, datetime
from pathlib import Path

from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

DATABASE_URL = os.environ.get("DATABASE_URL", "postgresql://tasks:tasks@localhost:5432/tasks")
DATA_DIR = Path(os.getenv("DATA_DIR", "data"))

FREQUENCIES = ("once", "daily", "weekly", "monthly", "yearly")

# The CSV format is the contract: export and import use the same columns.
DB_FIELDS = ["id", "title", "frequency", "tag", "start_date",
             "end_date", "next_date", "synced"]
USED_FIELDS = ["id", "task_id", "title", "tag", "due_date", "done"]

pool = ConnectionPool(
    DATABASE_URL,
    min_size=1,
    max_size=5,
    open=False,
    kwargs={"row_factory": dict_row},
)

SCHEMA = """
CREATE TABLE IF NOT EXISTS task_db (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      TEXT    NOT NULL,
    frequency  TEXT    NOT NULL
               CHECK (frequency IN ('once','daily','weekly','monthly','yearly')),
    tag        TEXT    NOT NULL DEFAULT '',
    start_date DATE    NOT NULL,
    end_date   DATE,
    next_date  DATE,
    synced     BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS task_used (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id  INTEGER NOT NULL REFERENCES task_db(id) ON DELETE CASCADE,
    title    TEXT    NOT NULL,
    tag      TEXT    NOT NULL DEFAULT '',
    due_date DATE    NOT NULL,
    done     BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS task_used_due_idx ON task_used (due_date);
"""


class CsvError(Exception):
    """Raised when a CSV file cannot be imported. The message says why."""


# ---------------------------------------------------------------- schema

def init_schema() -> None:
    with pool.connection() as conn:
        conn.execute(SCHEMA)


def ping() -> bool:
    with pool.connection() as conn:
        conn.execute("SELECT 1")
    return True


# ------------------------------------------------------------ CSV parsing

def _parse_date(value: str, where: str, required: bool) -> date | None:
    value = value.strip()
    if not value:
        if required:
            raise CsvError(f"{where}: a date is required")
        return None
    try:
        return date.fromisoformat(value)
    except ValueError:
        raise CsvError(f"{where}: '{value}' is not a date (use YYYY-MM-DD)")


def _parse_bool(value: str, where: str) -> bool:
    v = value.strip().lower()
    if v in ("true", "false"):
        return v == "true"
    raise CsvError(f"{where}: '{value}' must be true or false")


def _parse_int(value: str, where: str) -> int:
    try:
        return int(value)
    except ValueError:
        raise CsvError(f"{where}: '{value}' is not a whole number")


def _read_csv(path: Path, fields: list[str]) -> list[dict]:
    if not path.exists():
        raise CsvError(f"{path}: file not found")
    with path.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        missing = [c for c in fields if c not in (reader.fieldnames or [])]
        if missing:
            raise CsvError(f"{path.name}: missing columns {', '.join(missing)}")
        return list(reader)


def read_dir(src: Path, used_required: bool = True) -> tuple[list[dict], list[dict]]:
    """Read and validate task_db.csv and task_used.csv from a folder.

    Nothing touches the database here, so a bad file fails early.
    """
    db_rows = []
    for n, r in enumerate(_read_csv(src / "task_db.csv", DB_FIELDS), start=2):
        w = f"task_db.csv line {n}"
        freq = r["frequency"].strip().lower()
        if freq not in FREQUENCIES:
            raise CsvError(f"{w}: frequency '{r['frequency']}' must be one of {', '.join(FREQUENCIES)}")
        if not r["title"].strip():
            raise CsvError(f"{w}: title is required")
        start = _parse_date(r["start_date"], f"{w}, start_date", True)
        end = _parse_date(r["end_date"], f"{w}, end_date", False)
        if end and end < start:
            raise CsvError(f"{w}: end_date is before start_date")
        db_rows.append({
            "id": _parse_int(r["id"], f"{w}, id"),
            "title": r["title"].strip(),
            "frequency": freq,
            "tag": r["tag"].strip(),
            "start_date": start,
            "end_date": end,
            "next_date": _parse_date(r["next_date"], f"{w}, next_date", False),
            "synced": _parse_bool(r["synced"], f"{w}, synced"),
        })
    ids = [r["id"] for r in db_rows]
    if len(ids) != len(set(ids)):
        raise CsvError("task_db.csv: duplicate ids")

    used_path = src / "task_used.csv"
    used_rows = []
    if used_required or used_path.exists():
        for n, r in enumerate(_read_csv(used_path, USED_FIELDS), start=2):
            w = f"task_used.csv line {n}"
            task_id = _parse_int(r["task_id"], f"{w}, task_id")
            if task_id not in ids:
                raise CsvError(f"{w}: task_id {task_id} does not exist in task_db.csv")
            used_rows.append({
                "id": _parse_int(r["id"], f"{w}, id"),
                "task_id": task_id,
                "title": r["title"].strip(),
                "tag": r["tag"].strip(),
                "due_date": _parse_date(r["due_date"], f"{w}, due_date", True),
                "done": _parse_bool(r["done"], f"{w}, done"),
            })
        used_ids = [r["id"] for r in used_rows]
        if len(used_ids) != len(set(used_ids)):
            raise CsvError("task_used.csv: duplicate ids")
    return db_rows, used_rows


# --------------------------------------------------------------- import

def _realign(conn) -> None:
    """Next generated id = max(id) + 1, so new inserts never collide."""
    for table in ("task_db", "task_used"):
        conn.execute(
            f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
            f"COALESCE((SELECT MAX(id) FROM {table}), 0) + 1, false)"
        )


def _insert_all(conn, db_rows: list[dict], used_rows: list[dict]) -> None:
    for r in db_rows:
        conn.execute(
            "INSERT INTO task_db (id, title, frequency, tag, start_date, end_date, next_date, synced) "
            "VALUES (%(id)s, %(title)s, %(frequency)s, %(tag)s, %(start_date)s, "
            "%(end_date)s, %(next_date)s, %(synced)s)", r)
    for r in used_rows:
        conn.execute(
            "INSERT INTO task_used (id, task_id, title, tag, due_date, done) "
            "VALUES (%(id)s, %(task_id)s, %(title)s, %(tag)s, %(due_date)s, %(done)s)", r)
    _realign(conn)


def seed() -> bool:
    """Import the CSVs once, only if task_db is empty. Returns True if it imported."""
    with pool.connection() as conn:
        empty = conn.execute("SELECT NOT EXISTS (SELECT 1 FROM task_db) AS e").fetchone()["e"]
        if not empty:
            return False
        if not (DATA_DIR / "task_db.csv").exists():
            return False
        db_rows, used_rows = read_dir(DATA_DIR, used_required=False)
        _insert_all(conn, db_rows, used_rows)
        return True


def reset_from(src: Path) -> tuple[Path, int, int]:
    """Validate src, back up the current state, then replace everything.

    The replace runs in one transaction: if it fails, the old data stays.
    Returns (backup_folder, task_db_rows, task_used_rows).
    """
    db_rows, used_rows = read_dir(src)          # fails early on a bad file
    backup = export_to(DATA_DIR / "backups" / _stamp())
    with pool.connection() as conn:             # one transaction
        conn.execute("DELETE FROM task_used")
        conn.execute("DELETE FROM task_db")
        _insert_all(conn, db_rows, used_rows)
    return backup, len(db_rows), len(used_rows)


# --------------------------------------------------------------- export

def _stamp() -> str:
    return datetime.now().strftime("%Y-%m-%d_%H%M%S")


def _cell(value) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, date):
        return value.isoformat()
    return str(value)


def _write_csv(path: Path, fields: list[str], rows: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(fields)
        for r in rows:
            w.writerow([_cell(r[c]) for c in fields])


def export_to(folder: Path) -> Path:
    folder.mkdir(parents=True, exist_ok=True)
    with pool.connection() as conn:
        db_rows = conn.execute("SELECT * FROM task_db ORDER BY id").fetchall()
        used_rows = conn.execute("SELECT * FROM task_used ORDER BY id").fetchall()
    _write_csv(folder / "task_db.csv", DB_FIELDS, db_rows)
    _write_csv(folder / "task_used.csv", USED_FIELDS, used_rows)
    return folder


def default_export_folder() -> Path:
    return DATA_DIR / "exports" / _stamp()
